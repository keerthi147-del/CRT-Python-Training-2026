# Topics: Tuples, Lists and Sets


# --------------------------------------------------
# 1. CREATING TUPLES
# --------------------------------------------------

# Empty tuple
t1 = ()
print(t1)

# Empty tuple using tuple()
t2 = tuple()
print(t2)

# Single element tuple
t3 = (10,)
print(t3)

# Another way to create a single element tuple
t4 = 10,
print(t4)

# Multiple elements
t5 = (10, 20, 30, 40, 50)
print(t5)


# --------------------------------------------------
# 2. TUPLE WITH DIFFERENT DATA TYPES
# --------------------------------------------------

t = (10, 20, 'Keerthi', 9.0 + 3j)
print(t)


# --------------------------------------------------
# 3. TUPLE INDEXING
# --------------------------------------------------

t = (10, 20, 30)

print(t[0])
print(t[1])
print(t[2])


# --------------------------------------------------
# 4. CONVERTING TUPLE TO LIST
# --------------------------------------------------

t = (10, 20, 30)

l = list(t)
l.append(40)

print(l)


# --------------------------------------------------
# 5. CREATING LISTS
# --------------------------------------------------

# Empty list
l1 = []
print(l1)

# Empty list using list()
l2 = list()
print(l2)

# List with multiple elements
l3 = [10, 20, 30, 40, 50]
print(l3)


# --------------------------------------------------
# 6. APPEND METHOD
# --------------------------------------------------

l = [10, 20, 30]

l.append(40)

print(l)


# --------------------------------------------------
# 7. EXTEND METHOD
# --------------------------------------------------

l = [10, 20, 30]

l.extend([40, 50, 60])

print(l)


# --------------------------------------------------
# 8. INSERT METHOD
# --------------------------------------------------

l = [10, 20, 30]

l.insert(1, 15)

print(l)


# --------------------------------------------------
# 9. REMOVE METHOD
# --------------------------------------------------

l = [10, 20, 30, 40]

l.remove(20)

print(l)


# --------------------------------------------------
# 10. POP METHOD
# --------------------------------------------------

l = [10, 20, 30]

l.pop()

print(l)


# --------------------------------------------------
# 11. CLEAR METHOD
# --------------------------------------------------

l = [10, 20, 30]

l.clear()

print(l)


# --------------------------------------------------
# 12. INDEX METHOD
# --------------------------------------------------

l = [10, 20, 30]

print(l.index(20))


# --------------------------------------------------
# 13. COUNT METHOD
# --------------------------------------------------

l = [10, 20, 10, 30, 10]

print(l.count(10))


# --------------------------------------------------
# 14. ACCESSING LIST ELEMENTS
# --------------------------------------------------

l = [1, 2, 3]

print(l[0])
print(l[1])
print(l[2])


# --------------------------------------------------
# 15. NESTED LIST
# --------------------------------------------------

my_list = [[1, 2, 3], [4, 5, 6], [7, 8, 9]]

print(my_list[0])
print(my_list[1])
print(my_list[2])

print(my_list[0][1])


# --------------------------------------------------
# 16. CREATING SETS
# --------------------------------------------------

# Empty set
s1 = set()
print(s1)

# Set with elements
s2 = {10, 20, 30}
print(s2)


# --------------------------------------------------
# 17. DUPLICATES IN A SET
# --------------------------------------------------

s = {10, 20, 10, 30, 20}

print(s)


# --------------------------------------------------
# 18. ADD METHOD
# --------------------------------------------------

s = {10, 20, 30}

s.add(40)

print(s)


# --------------------------------------------------
# 19. UPDATE METHOD
# --------------------------------------------------

s = {10, 20, 30}

s.update([40, 50])

print(s)


# --------------------------------------------------
# 20. REMOVE METHOD IN SET
# --------------------------------------------------

s = {10, 20, 30}

s.remove(20)

print(s)


# --------------------------------------------------
# 21. DISCARD METHOD
# --------------------------------------------------

s = {10, 20, 30}

s.discard(20)

print(s)


# --------------------------------------------------
# 22. SET WITH DIFFERENT TYPES OF ELEMENTS
# --------------------------------------------------

s = {10, 20, 'Python'}

print(s)


# --------------------------------------------------
# 23. LIST VS TUPLE VS SET
# --------------------------------------------------

my_list = [10, 20, 10, 30]
my_tuple = (10, 20, 10, 30)
my_set = {10, 20, 10, 30}

print('List:', my_list)
print('Tuple:', my_tuple)
print('Set:', my_set)



# ------------------------------------------
# 1. Creating a List
# ------------------------------------------

list1 = [10, 40, 890]

print(list1)


# ------------------------------------------
# 2. List with Different Data Types
# ------------------------------------------

list1 = [10, 'Keerthi', 20.5, True]

print(list1)


# ------------------------------------------
# 3. Creating a List Using list()
# ------------------------------------------

list1 = list((10, 20, 30))

print(list1)


# ------------------------------------------
# 4. Accessing List Elements
# ------------------------------------------

list1 = [10, 20, 30, 40, 50]

print(list1[0])
print(list1[2])


# ------------------------------------------
# 5. Positive Indexing
# ------------------------------------------

list1 = [10, 20, 30, 40, 50]

print(list1[0])
print(list1[1])
print(list1[2])
print(list1[3])
print(list1[4])


# ------------------------------------------
# 6. Negative Indexing
# ------------------------------------------

list1 = [10, 20, 30, 40, 50]

print(list1[-1])
print(list1[-2])
print(list1[-3])


# ------------------------------------------
# 7. List Slicing
# ------------------------------------------

list1 = [10, 20, 30, 40, 50]

print(list1[1:4])


# ------------------------------------------
# 8. List Slicing with Step Value
# ------------------------------------------

list1 = [10, 20, 30, 40, 50, 60]

print(list1[1:6:2])


# ------------------------------------------
# 9. append() Method
# ------------------------------------------

list1 = []

list1.append(10)

print(list1)


# ------------------------------------------
# 10. Adding Multiple Elements Using append()
# ------------------------------------------

list1 = []

list1.append(10)
list1.append(20)
list1.append(30)

print(list1)


# ------------------------------------------
# 11. extend() Method
# ------------------------------------------

list1 = []

list1.extend([10, 20, 30])

print(list1)


# ------------------------------------------
# 12. Difference Between append() and extend()
# ------------------------------------------

list1 = []

list1.append([10, 20, 30])

print(list1)


list2 = []

list2.extend([10, 20, 30])

print(list2)


# ------------------------------------------
# 13. insert() Method
# ------------------------------------------

list1 = [10, 20, 30]

list1.insert(1, 15)

print(list1)


# ------------------------------------------
# 14. remove() Method
# ------------------------------------------

list1 = [10, 20, 30, 20]

list1.remove(20)

print(list1)


# ------------------------------------------
# 15. pop() Method
# ------------------------------------------

list1 = [10, 20, 30]

list1.pop()

print(list1)


# ------------------------------------------
# 16. pop() Using Index
# ------------------------------------------

list1 = [10, 20, 30]

list1.pop(1)

print(list1)


# ------------------------------------------
# 17. del Keyword
# ------------------------------------------

list1 = [10, 20, 30]

del list1[1]

print(list1)


# ------------------------------------------
# 18. clear() Method
# ------------------------------------------

list1 = [10, 20, 30]

list1.clear()

print(list1)


# ------------------------------------------
# 19. Nested List
# ------------------------------------------

list1 = [10, 20, [30, 40], 50]

print(list1)


# ------------------------------------------
# 20. Accessing Nested List
# ------------------------------------------

list1 = [10, 20, [30, 40], 50]

print(list1[2])
print(list1[2][0])
print(list1[2][1])


# ------------------------------------------
# 21. Modifying List Elements
# ------------------------------------------

list1 = [10, 20, 30]

list1[1] = 25

print(list1)


# ------------------------------------------
# 22. List with Duplicate Elements
# ------------------------------------------

list1 = [10, 20, 10, 30, 20]

print(list1)


# ------------------------------------------
# 23. List with Different Data Types
# ------------------------------------------

list1 = [10, 'Keerthi', 20.5, True]

print(list1)


